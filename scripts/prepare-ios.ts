import { execFileSync } from 'node:child_process';
import { randomUUID } from 'node:crypto';
import { constants } from 'node:fs';
import {
  access,
  readFile,
  readdir,
  realpath,
  rename,
  stat,
  unlink,
  writeFile,
} from 'node:fs/promises';
import { delimiter, dirname, isAbsolute, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const environment_name = '.apell-build-env';
const bootstrap = [
  '# Apell: load the local tool paths prepared by pnpm ios:prepare.',
  'if [ ! -r "${PROJECT_DIR:?}/.apell-build-env" ]; then',
  "  printf '%s\\n' 'Run pnpm ios:prepare in the app project before building with Xcode.' >&2",
  '  exit 1',
  'fi',
  '. "${PROJECT_DIR:?}/.apell-build-env"',
  '',
].join('\n');

export function shellQuote(value: string): string {
  return `'${value.replaceAll("'", "'\\''")}'`;
}

export function buildEnvironment(tool_directories: readonly string[]): string {
  if (
    tool_directories.length === 0 ||
    tool_directories.some(
      (directory) => !isAbsolute(directory) || directory.includes(':') || directory.includes('\0'),
    )
  ) {
    throw new Error('Build tool directories must be absolute paths without PATH separators.');
  }
  const stable_path = [...new Set(tool_directories)].join(':');
  return [
    '# Generated by pnpm ios:prepare. Local machine paths; do not commit this file.',
    `export PATH=${shellQuote(stable_path)}:"\${PATH:-/usr/bin:/bin:/usr/sbin:/sbin}"`,
    '',
  ].join('\n');
}

function patchRustScript(source: string): string {
  const original = source.startsWith(bootstrap) ? source.slice(bootstrap.length) : source;
  if (!/^pnpm tauri ios xcode-script(?: [^\r\n]*)?\n?$/.test(original)) {
    throw new Error(
      'Unexpected Build Rust Code script; expected the generated pnpm Tauri command.',
    );
  }
  return bootstrap + original;
}

export function patchProjectYaml(source: string): string {
  const names = [
    ...source.matchAll(
      /^([ ]*)name: (?:Build Rust Code|"Build Rust Code"|'Build Rust Code')[ \t]*(?:\r?\n|$)/gm,
    ),
  ];
  if (names.length !== 1 || names[0][1].length < 2) {
    throw new Error('Expected exactly one Build Rust Code phase in the generated project.yml.');
  }
  const name = names[0];
  const header_pattern = new RegExp(`^ {${name[1].length - 2}}- script: \\|[ \\t]*\\r?\\n`, 'gm');
  const headers = [...source.slice(0, name.index).matchAll(header_pattern)];
  const header = headers.at(-1);
  if (!header) {
    throw new Error('Unexpected Build Rust Code block in the generated project.yml.');
  }
  const start = header.index! + header[0].length;
  const body = source.slice(start, name.index);
  const indentation = ' '.repeat(name[1].length + 2);
  const lines = body.split(/\r?\n/);
  lines.pop();
  if (lines.length === 0 || lines.some((line) => line && !line.startsWith(indentation))) {
    throw new Error('Unexpected Build Rust Code indentation in the generated project.yml.');
  }
  const script = lines.map((line) => line.slice(indentation.length)).join('\n') + '\n';
  const newline = header[0].endsWith('\r\n') ? '\r\n' : '\n';
  const patched = patchRustScript(script)
    .split('\n')
    .slice(0, -1)
    .map((line) => indentation + line)
    .join(newline);
  return source.slice(0, start) + patched + newline + source.slice(name.index);
}

export function patchPbxProject(source: string): string {
  const sections = [
    ...source.matchAll(
      /\/\* Begin PBXShellScriptBuildPhase section \*\/[\s\S]*?\/\* End PBXShellScriptBuildPhase section \*\//g,
    ),
  ];
  if (sections.length !== 1) {
    throw new Error('Expected one shell script section in the generated Xcode project.');
  }
  const section = sections[0];
  const phases = [
    ...section[0].matchAll(
      /^([ \t]*)[A-Fa-f0-9]{24} \/\* Build Rust Code \*\/ = \{\r?\n[\s\S]*?^\1\};/gm,
    ),
  ];
  if (phases.length !== 1) {
    throw new Error('Expected exactly one Build Rust Code phase in the generated Xcode project.');
  }
  const phase = phases[0];
  if (
    !/^\s*isa = PBXShellScriptBuildPhase;$/m.test(phase[0]) ||
    !/^\s*name = "Build Rust Code";$/m.test(phase[0]) ||
    !/^\s*shellPath = \/bin\/sh;$/m.test(phase[0])
  ) {
    throw new Error('Unexpected Build Rust Code phase settings in the generated Xcode project.');
  }
  const scripts = [...phase[0].matchAll(/\bshellScript = ("(?:\\.|[^"\\])*");/g)];
  if (scripts.length !== 1) {
    throw new Error('Expected exactly one Build Rust Code shell script in the Xcode project.');
  }
  const script = scripts[0];
  let decoded: string;
  try {
    decoded = JSON.parse(script[1]) as string;
  } catch {
    throw new Error('Unexpected escaping in the generated Build Rust Code shell script.');
  }
  const patched = JSON.stringify(patchRustScript(decoded));
  const start = section.index! + phase.index! + script.index! + 'shellScript = '.length;
  return source.slice(0, start) + patched + source.slice(start + script[1].length);
}

async function executableDirectory(executable: string): Promise<string> {
  await access(executable, constants.X_OK);
  if (!(await stat(executable)).isFile()) throw new Error('Not an executable file.');
  // Resolve the directory, preserving shim names such as pnpm -> corepack/pnpm.js.
  return realpath(dirname(executable));
}

export async function resolveToolDirectories(
  search_path: string = process.env.PATH ?? '',
  node_executable: string = process.execPath,
): Promise<string[]> {
  const directories: string[] = [];
  try {
    directories.push(await executableDirectory(node_executable));
  } catch {
    throw new Error('Cannot locate Node.js. Run pnpm ios:prepare from a configured terminal.');
  }
  for (const tool of ['pnpm', 'cargo', 'rustup']) {
    let directory: string | undefined;
    for (const candidate of search_path.split(delimiter).filter(isAbsolute)) {
      try {
        directory = await executableDirectory(join(candidate, tool));
        break;
      } catch {
        // Continue searching PATH, ignoring stale or non-executable entries.
      }
    }
    if (!directory) {
      throw new Error(`Cannot locate ${tool}. Run pnpm ios:prepare from a configured terminal.`);
    }
    directories.push(directory);
  }
  return [...new Set(directories)];
}

export interface PrepareIosOptions {
  project_root?: string;
  search_path?: string;
  node_executable?: string;
}

export async function prepareIos(options: PrepareIosOptions = {}): Promise<void> {
  const project_root = options.project_root ?? fileURLToPath(new URL('..', import.meta.url));
  const apple_dir = join(project_root, 'src-tauri', 'gen', 'apple');
  let projects: string[];
  try {
    projects = (await readdir(apple_dir, { withFileTypes: true }))
      .filter((entry) => entry.isDirectory() && entry.name.endsWith('.xcodeproj'))
      .map((entry) => entry.name);
  } catch {
    throw new Error('The generated iOS project is missing. Run pnpm ios:init first.');
  }
  if (projects.length !== 1) {
    throw new Error('Expected exactly one generated Xcode project. Run pnpm ios:init first.');
  }
  const yaml_path = join(apple_dir, 'project.yml');
  const pbx_path = join(apple_dir, projects[0], 'project.pbxproj');
  let originals: string[];
  try {
    originals = await Promise.all([readFile(yaml_path, 'utf8'), readFile(pbx_path, 'utf8')]);
  } catch {
    throw new Error('Cannot read the generated iOS project files. Run pnpm ios:init first.');
  }
  // Validate both files before changing either, preserving local signing settings.
  const patched = [patchProjectYaml(originals[0]), patchPbxProject(originals[1])];
  const environment = buildEnvironment(
    await resolveToolDirectories(options.search_path, options.node_executable),
  );
  try {
    execFileSync('git', ['check-ignore', '--quiet', '--', 'src-tauri/gen/apple/.apell-build-env'], {
      cwd: project_root,
      stdio: 'ignore',
    });
  } catch {
    throw new Error('The local iOS build environment must be ignored by Git before preparation.');
  }
  const temporary = join(apple_dir, `${environment_name}.${randomUUID()}.tmp`);
  try {
    await writeFile(temporary, environment, { mode: 0o600, flag: 'wx' });
    await rename(temporary, join(apple_dir, environment_name));
    if (patched[0] !== originals[0]) await writeFile(yaml_path, patched[0]);
    if (patched[1] !== originals[1]) await writeFile(pbx_path, patched[1]);
  } catch {
    throw new Error('Could not update the local iOS build setup. Check project file permissions.');
  } finally {
    await unlink(temporary).catch(() => {});
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    await prepareIos();
    console.log('iOS build tool paths prepared. Keep the Tauri CLI running while Xcode builds.');
  } catch (error) {
    console.error(
      error instanceof Error ? error.message : 'Could not prepare the iOS build setup.',
    );
    process.exitCode = 1;
  }
}
